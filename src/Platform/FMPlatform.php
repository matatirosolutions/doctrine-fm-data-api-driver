<?php

declare(strict_types=1);

namespace MSDev\DoctrineFMDataAPIDriver\Platform;

use Doctrine\DBAL\Connection;
use Doctrine\DBAL\Platforms\AbstractPlatform;
use Doctrine\DBAL\Platforms\DateIntervalUnit;
use Doctrine\DBAL\Platforms\Exception\NotSupported;
use Doctrine\DBAL\Platforms\Keywords\KeywordList;
use Doctrine\DBAL\Schema\AbstractSchemaManager;
use Doctrine\DBAL\Schema\TableDiff;
use Doctrine\DBAL\TransactionIsolationLevel;
use MSDev\DoctrineFMDataAPIDriver\Driver\FMStatement;

/**
 * The SQL dialect Doctrine speaks to the driver.
 *
 * Only DML is ever translated into Data API requests, so there is no schema management
 * (FileMaker's schema is defined in FileMaker, not in code) and the schema related methods
 * simply report that they aren't supported.
 */
class FMPlatform extends AbstractPlatform
{
    protected function initializeDoctrineTypeMappings(): void
    {
        $this->doctrineTypeMapping = [
            'smallint'  => 'smallint',
            'bigint'    => 'bigint',
            'integer'   => 'integer',
            'time'      => 'time',
            'date'      => 'date',
            'varchar'   => 'string',
            'character' => 'string',
            'varbinary' => 'binary',
            'binary'    => 'binary',
            'clob'      => 'text',
            'blob'      => 'blob',
            'decimal'   => 'decimal',
            'double'    => 'float',
            'real'      => 'float',
            'timestamp' => 'datetime',
        ];
    }

    public function getBooleanTypeDeclarationSQL(array $column): string
    {
        return 'SMALLINT';
    }

    public function getIntegerTypeDeclarationSQL(array $column): string
    {
        return 'INTEGER' . $this->_getCommonIntegerTypeDeclarationSQL($column);
    }

    public function getBigIntTypeDeclarationSQL(array $column): string
    {
        return 'BIGINT' . $this->_getCommonIntegerTypeDeclarationSQL($column);
    }

    public function getSmallIntTypeDeclarationSQL(array $column): string
    {
        return 'SMALLINT' . $this->_getCommonIntegerTypeDeclarationSQL($column);
    }

    protected function _getCommonIntegerTypeDeclarationSQL(array $column): string
    {
        return empty($column['autoincrement']) ? '' : ' GENERATED BY DEFAULT AS IDENTITY';
    }

    public function getClobTypeDeclarationSQL(array $column): string
    {
        return 'CLOB(1M)';
    }

    public function getBlobTypeDeclarationSQL(array $column): string
    {
        return 'BLOB(1M)';
    }

    public function getDateTimeTypeDeclarationSQL(array $column): string
    {
        return 'TIMESTAMP(0)';
    }

    public function getDateTypeDeclarationSQL(array $column): string
    {
        return 'DATE';
    }

    public function getTimeTypeDeclarationSQL(array $column): string
    {
        return 'TIME';
    }

    protected function getVarcharTypeDeclarationSQLSnippet(?int $length): string
    {
        return 'VARCHAR(' . ($length ?? 255) . ')';
    }

    protected function getBinaryTypeDeclarationSQLSnippet(?int $length): string
    {
        return 'VARBINARY(' . ($length ?? 255) . ')';
    }

    protected function getDateArithmeticIntervalExpression(
        string $date,
        string $operator,
        string $interval,
        DateIntervalUnit $unit,
    ): string {
        if (DateIntervalUnit::WEEK === $unit) {
            $interval = '(' . $interval . ' * 7)';
            $unit = DateIntervalUnit::DAY;
        } elseif (DateIntervalUnit::QUARTER === $unit) {
            $interval = '(' . $interval . ' * 3)';
            $unit = DateIntervalUnit::MONTH;
        }

        return $date . ' ' . $operator . ' ' . $interval . ' ' . $unit->value;
    }

    public function getDateDiffExpression(string $date1, string $date2): string
    {
        return 'DAYS(' . $date1 . ') - DAYS(' . $date2 . ')';
    }

    public function getLocateExpression(string $string, string $substring, ?string $start = null): string
    {
        if (null === $start) {
            return 'LOCATE(' . $substring . ', ' . $string . ')';
        }

        return 'LOCATE(' . $substring . ', ' . $string . ', ' . $start . ')';
    }

    public function getCurrentDatabaseExpression(): string
    {
        throw NotSupported::new(__METHOD__);
    }

    /**
     * FileMaker has no limit clause, so a limit is expressed as a row number range which
     * FMStatement later turns into the Data API's offset and limit.
     */
    protected function doModifyLimitQuery(string $query, ?int $limit, int $offset): string
    {
        $where = [];

        if ($offset > 0) {
            $where[] = sprintf('db22.DC_ROWNUM >= %d', $offset + 1);
        }

        if (null !== $limit) {
            $where[] = sprintf('db22.DC_ROWNUM <= %d', $offset + $limit);
        }

        if (empty($where)) {
            return $query;
        }

        return sprintf(
            'SELECT db22.* FROM (SELECT db21.*, ROW_NUMBER() OVER() AS DC_ROWNUM FROM (%s) db21) db22 WHERE %s',
            $query,
            implode(' AND ', $where)
        );
    }

    public function supportsIdentityColumns(): bool
    {
        return true;
    }

    /**
     * Doctrine uses savepoints to nest transactions. FMStatement recognises the savepoint statements
     * and applies them to the writes which the connection is holding back.
     */
    public function supportsSavepoints(): bool
    {
        return true;
    }

    public function getAlterTableSQL(TableDiff $diff): array
    {
        throw NotSupported::new(__METHOD__);
    }

    public function getListViewsSQL(string $database): string
    {
        throw NotSupported::new(__METHOD__);
    }

    public function getSetTransactionIsolationSQL(TransactionIsolationLevel $level): string
    {
        throw NotSupported::new(__METHOD__);
    }

    protected function createReservedKeywordsList(): KeywordList
    {
        return new FMKeywords();
    }

    public function createSchemaManager(Connection $connection): AbstractSchemaManager
    {
        throw NotSupported::new('code-based schema changes are not supported; ' . __METHOD__);
    }
}
